/**
 * Dynamic content filler: ensures that for ANY chosen combination of country or niche,
 * there are always multiple engaging reels displayed.
 */
export function ensureRichContent(
  currentReels: Reel[],
  continent: ContinentId,
  country: CountryId,
  niche: Niche
): Reel[] {
  let matched = currentReels.filter((r) => {
    if (continent !== 'all' && r.continent !== continent) return false;
    if (country !== 'all' && r.country !== country) return false;
    if (niche !== 'all' && r.niche !== niche) return false;
    return true;
  });

  // If there are already 4 or more reels, return as-is
  if (matched.length >= 4) {
    return currentReels;
  }

  // Otherwise generate dynamic regional reels
  const targetCountry = COUNTRIES.find((c) => c.id === country) ||
    COUNTRIES.find((c) => continent !== 'all' && c.continent === continent) ||
    COUNTRIES[0];
  const targetContinent = targetCountry.continent;
  const targetNiche = niche !== 'all' ? niche : 'ai_tech';

  const nicheMeta = ALL_NICHES.find((n) => n.id === targetNiche) || ALL_NICHES[1];

  const generatedCount = 4 - matched.length;
  const newItems: Reel[] = [];

  for (let i = 0; i < generatedCount; i++) {
    const isTt = i % 2 === 0;
    const rank = matched.length + i + 1;
    const media = getNicheMedia(targetNiche);

    newItems.push({
      id: `gen-${targetCountry.id}-${targetNiche}-${rank}-${Date.now()}`,
      platform: isTt ? 'tiktok' : 'instagram',
      title: `${targetCountry.flag} Трендовый контент: ${nicheMeta.label} (#${rank})`,
      description: `Вирусный ролик, набирающий обороты в регионе ${targetCountry.label}. Потрясающая динамика и охваты! #trend #${targetNiche} #${targetCountry.code.toLowerCase()}`,
      authorName: `${targetCountry.code} Creator ${rank}`,
      authorUsername: `@${targetCountry.code.toLowerCase()}_viral_${rank}`,
      authorAvatar: `https://images.unsplash.com/photo-1534528741775?w=150&auto=format&fit=crop&q=80`,
      authorVerified: rank % 2 === 1,
      authorFollowers: 300000 + rank * 125000,
      niche: targetNiche,
      continent: targetContinent,
      country: targetCountry.id,
      countryFlag: targetCountry.flag,
      countryName: targetCountry.label,
      hashtags: [`#${targetCountry.code.toLowerCase()}`, `#trend`, `#${targetNiche}`, `#viral`],
      soundTitle: media.soundTitle,
      soundAuthor: media.soundAuthor,
      soundIsTrending: true,
      publishedAt: new Date(Date.now() - 3600000 * rank).toISOString(),
      trendingRank: rank,
      rankChange: 'new',
      rankChangeDelta: 0,
      thumbnailUrl: `${baseUrl}thumbnails/poster-${targetNiche}-${(rank % 4) + 1}.jpg`,
      videoUrl: media.video,
      backupVideoUrl: WIKIMEDIA_STREAM,
      audioUrl: media.audio,
      originalUrl: isTt
        ? `https://www.tiktok.com/@${targetCountry.code.toLowerCase()}_viral_${rank}/video/7420918274019288${(200 + rank).toString().padStart(3, '0')}`
        : `https://www.instagram.com/reel/D${targetCountry.code.toUpperCase()}${targetNiche.slice(0, 3).toUpperCase()}${200 + rank}xK/`,
      durationSeconds: 25 + rank * 3,
      metrics: {
        views: 1200000 + rank * 350000,
        likes: 180000 + rank * 45000,
        comments: 6500 + rank * 1200,
        shares: 42000 + rank * 8500,
        saves: 85000 + rank * 14000,
        engagementRate: 21.5 + (rank % 5),
        velocityScore: 35.0 + rank * 6.5,
        viewsGrowthLastHour: 95000 + rank * 22000,
      },
      createdAt: new Date().toISOString(),
      updatedAt: new Date().toISOString(),
    });
  }

  return [...currentReels, ...newItems];
}

export function simulateRealtimeTick(reels: Reel[]): Reel[] {
  const updated = reels.map((reel) => {
    const baseGrowth = Math.floor(Math.random() * 16500) + 1500;
    const velocityMultiplier = 1 + reel.metrics.velocityScore / 100;
    const viewsInc = Math.floor(baseGrowth * velocityMultiplier);

    const likesInc = Math.floor(viewsInc * (Math.random() * 0.08 + 0.04));
    const commentsInc = Math.floor(likesInc * (Math.random() * 0.05 + 0.01));
    const sharesInc = Math.floor(likesInc * (Math.random() * 0.25 + 0.1));
    const savesInc = Math.floor(likesInc * (Math.random() * 0.35 + 0.15));

    const newViews = reel.metrics.views + viewsInc;
    const newLikes = reel.metrics.likes + likesInc;
    const newComments = reel.metrics.comments + commentsInc;
    const newShares = reel.metrics.shares + sharesInc;
    const newSaves = reel.metrics.saves + savesInc;

    const newEngagementRate = parseFloat(
      (((newLikes + newComments + newShares + newSaves) / newViews) * 100).toFixed(1)
    );

    const velocityDelta = Math.random() * 8 - 3;
    const newVelocity = Math.max(5, parseFloat((reel.metrics.velocityScore + velocityDelta).toFixed(1)));

    return {
      ...reel,
      metrics: {
        ...reel.metrics,
        views: newViews,
        likes: newLikes,
        comments: newComments,
        shares: newShares,
        saves: newSaves,
        engagementRate: newEngagementRate,
        velocityScore: newVelocity,
        viewsGrowthLastHour: reel.metrics.viewsGrowthLastHour + viewsInc,
      },
      updatedAt: new Date().toISOString(),
    };
  });

  return updatePlatformRanks(updated);
}

function updatePlatformRanks(reels: Reel[]): Reel[] {
  const platforms: ('tiktok' | 'instagram')[] = ['tiktok', 'instagram'];
  let result: Reel[] = [];

  for (const plat of platforms) {
    const platReels = reels.filter((r) => r.platform === plat);
    const sorted = [...platReels].sort((a, b) => {
      const scoreA = a.metrics.views * 0.3 + a.metrics.velocityScore * 50000;
      const scoreB = b.metrics.views * 0.3 + b.metrics.velocityScore * 50000;
      return scoreB - scoreA;
    });

    const reranked = sorted.map((item, index) => {
      const newRank = index + 1;
      let rankChange: 'up' | 'down' | 'same' | 'new' = 'same';
      let delta = 0;

      if (item.trendingRank > newRank) {
        rankChange = 'up';
        delta = item.trendingRank - newRank;
      } else if (item.trendingRank < newRank) {
        rankChange = 'down';
        delta = newRank - item.trendingRank;
      }

      return {
        ...item,
        trendingRank: newRank,
        rankChange,
        rankChangeDelta: delta,
      };
    });

    result = [...result, ...reranked];
  }

  return result;
}
